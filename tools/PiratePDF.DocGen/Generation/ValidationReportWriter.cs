using System.Globalization;
using System.Text;

using PiratePDF.DocGen.Validation;

namespace PiratePDF.DocGen.Generation;

internal static class ValidationReportWriter
{
    // =========================================================================
    // Public API
    // =========================================================================

    public static void Write(
        string outputPath,
        string repositoryRoot,
        int documentCount,
        DocumentationValidationResult result)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(outputPath);
        ArgumentException.ThrowIfNullOrWhiteSpace(repositoryRoot);
        ArgumentNullException.ThrowIfNull(result);

        if (documentCount < 0)
        {
            throw new ArgumentOutOfRangeException(
                nameof(documentCount),
                documentCount,
                "The document count cannot be negative.");
        }

        var report = BuildReport(
            repositoryRoot,
            documentCount,
            result);

        WriteAtomically(outputPath, report);
    }

    // =========================================================================
    // Report Generation
    // =========================================================================

    private static string BuildReport(
        string repositoryRoot,
        int documentCount,
        DocumentationValidationResult result)
    {
        var builder = new StringBuilder();

        builder.AppendLine("# PiratePDF Documentation Validation Report");
        builder.AppendLine();
        builder.AppendLine("> This file is generated by PiratePDF.DocGen.");
        builder.AppendLine("> Do not edit it manually.");
        builder.AppendLine();

        AppendInvariantLine(
            builder,
            "Generated: {0:yyyy-MM-dd HH:mm:ss} UTC",
            DateTimeOffset.UtcNow);

        builder.AppendLine();
        builder.AppendLine("## Summary");
        builder.AppendLine();
        builder.AppendLine("| Item | Count |");
        builder.AppendLine("|---|---:|");

        AppendInvariantLine(
            builder,
            "| Documents | {0} |",
            documentCount);

        AppendInvariantLine(
            builder,
            "| Errors | {0} |",
            result.ErrorCount);

        AppendInvariantLine(
            builder,
            "| Warnings | {0} |",
            result.WarningCount);

        AppendInvariantLine(
            builder,
            "| Information | {0} |",
            result.InformationCount);

        builder.AppendLine();

        if (result.Issues.Count == 0)
        {
            builder.AppendLine("## Result");
            builder.AppendLine();
            builder.AppendLine("All documentation passed validation.");

            return builder.ToString();
        }

        AppendIssues(
            builder,
            "Errors",
            ValidationSeverity.Error,
            repositoryRoot,
            result.Issues);

        AppendIssues(
            builder,
            "Warnings",
            ValidationSeverity.Warning,
            repositoryRoot,
            result.Issues);

        AppendIssues(
            builder,
            "Information",
            ValidationSeverity.Information,
            repositoryRoot,
            result.Issues);

        return builder.ToString();
    }

    private static void AppendIssues(
        StringBuilder builder,
        string heading,
        ValidationSeverity severity,
        string repositoryRoot,
        IReadOnlyList<ValidationIssue> issues)
    {
        var matchingIssues = issues
            .Where(issue => issue.Severity == severity)
            .ToArray();

        if (matchingIssues.Length == 0)
        {
            return;
        }

        AppendInvariantLine(
            builder,
            "## {0}",
            heading);

        builder.AppendLine();

        foreach (var issue in matchingIssues)
        {
            var relativePath = Path
                .GetRelativePath(repositoryRoot, issue.File)
                .Replace('\\', '/');

            AppendInvariantLine(
                builder,
                "### {0}",
                Escape(issue.DocumentId));

            builder.AppendLine();

            AppendInvariantLine(
                builder,
                "- **File:** `{0}`",
                Escape(relativePath));

            AppendInvariantLine(
                builder,
                "- **Message:** {0}",
                Escape(issue.Message));

            builder.AppendLine();
        }
    }

    // =========================================================================
    // File Output
    // =========================================================================

    private static void WriteAtomically(
        string outputPath,
        string content)
    {
        var fullOutputPath = Path.GetFullPath(outputPath);

        var outputDirectory = Path.GetDirectoryName(fullOutputPath)
            ?? throw new InvalidOperationException(
                "The report output directory could not be determined.");

        Directory.CreateDirectory(outputDirectory);

        var temporaryPath = Path.Combine(
            outputDirectory,
            $".{Path.GetFileName(fullOutputPath)}.{Guid.NewGuid():N}.tmp");

        try
        {
            TrackedGeneratedFileWriter.WriteIfChanged(
                temporaryPath,
                content,
                new UTF8Encoding(
                    encoderShouldEmitUTF8Identifier: false));

            File.Move(
                temporaryPath,
                fullOutputPath,
                overwrite: true);
        }
        finally
        {
            if (File.Exists(temporaryPath))
            {
                File.Delete(temporaryPath);
            }
        }
    }

    // =========================================================================
    // Formatting Helpers
    // =========================================================================

    private static void AppendInvariantLine(
        StringBuilder builder,
        string format,
        params object?[] arguments)
    {
        ArgumentNullException.ThrowIfNull(builder);
        ArgumentException.ThrowIfNullOrWhiteSpace(format);
        ArgumentNullException.ThrowIfNull(arguments);

        builder.AppendFormat(
            CultureInfo.InvariantCulture,
            format,
            arguments);

        builder.AppendLine();
    }

    private static string Escape(
        string value)
    {
        return value
            .Replace(
                "\\",
                "\\\\",
                StringComparison.Ordinal)
            .Replace(
                "|",
                "\\|",
                StringComparison.Ordinal);
    }
}