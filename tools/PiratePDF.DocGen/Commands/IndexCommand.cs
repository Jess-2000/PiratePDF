using System.Text;

using PiratePDF.DocGen.Infrastructure;
using PiratePDF.DocGen.Library;

namespace PiratePDF.DocGen.Commands;

internal sealed class IndexCommand : IDocGenCommand
{
    public string Name => "index";

    public string Description =>
        "Generate the documentation index.";

    // =========================================================================
    // Command Execution
    // =========================================================================

    public int Execute(
        CommandContext context,
        IReadOnlyList<string> arguments)
    {
        ArgumentNullException.ThrowIfNull(context);
        ArgumentNullException.ThrowIfNull(arguments);

        if (arguments.Count > 0)
        {
            return HandleArguments(arguments);
        }

        try
        {
            var library = LoadLibrary(context);

            GenerateIndex(
                context.DocumentationDirectory,
                context.DocumentationIndexPath,
                library.AllDocuments);

            Console.WriteLine(
                "Documentation index generated successfully.");

            Console.WriteLine();
            Console.WriteLine($"Documents: {library.Count}");
            Console.WriteLine(
                $"Output: {context.DocumentationIndexPath}");

            return 0;
        }
        catch (Exception exception)
        {
            Console.Error.WriteLine(
                "Documentation index generation failed.");

            Console.Error.WriteLine(exception);

            return 2;
        }
    }

    // =========================================================================
    // Documentation Library
    // =========================================================================

    private static DocumentationLibrary LoadLibrary(
        CommandContext context)
    {
        if (context.IsDocumentationLibraryLoaded)
        {
            return context.DocumentationLibrary;
        }

        var library = DocumentationLibraryLoader.Load(
            context.DocumentationDirectory);

        context.SetDocumentationLibrary(library);

        return library;
    }

    // =========================================================================
    // Index Generation
    // =========================================================================

    private static void GenerateIndex(
        string documentationDirectory,
        string outputPath,
        IReadOnlyCollection<DocumentationDocument> documents)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(
            documentationDirectory);

        ArgumentException.ThrowIfNullOrWhiteSpace(
            outputPath);

        ArgumentNullException.ThrowIfNull(documents);

        var builder = new StringBuilder();

        builder.AppendLine(
            "# PiratePDF Documentation Index");

        builder.AppendLine();

        builder.AppendLine(
            "> This file is generated by PiratePDF.DocGen.");

        builder.AppendLine(
            "> Do not edit it manually.");

        builder.AppendLine();

        builder.AppendLine(
            "| Document ID | Title | Category | Version | Status | Last Updated |");

        builder.AppendLine(
            "|---|---|---|---|---|---|");

        foreach (var document in documents)
        {
            AppendDocumentRow(
                builder,
                documentationDirectory,
                document);
        }

        WriteAtomically(
            outputPath,
            builder.ToString());
    }

    private static void AppendDocumentRow(
        StringBuilder builder,
        string documentationDirectory,
        DocumentationDocument document)
    {
        ArgumentNullException.ThrowIfNull(builder);

        ArgumentException.ThrowIfNullOrWhiteSpace(
            documentationDirectory);

        ArgumentNullException.ThrowIfNull(document);

        var relativePath = Path
            .GetRelativePath(
                documentationDirectory,
                document.FilePath)
            .Replace('\\', '/');

        builder.Append("| ");
        builder.Append(
            EscapeTableValue(document.DocumentId));

        builder.Append(" | [");
        builder.Append(
            EscapeTableValue(document.Title));

        builder.Append("](");
        builder.Append(
            EscapeLinkTarget(relativePath));

        builder.Append(") | ");
        builder.Append(
            EscapeTableValue(document.Category));

        builder.Append(" | ");
        builder.Append(
            EscapeTableValue(document.Version));

        builder.Append(" | ");
        builder.Append(
            EscapeTableValue(document.Status));

        builder.Append(" | ");
        builder.Append(
            EscapeTableValue(document.LastUpdated));

        builder.AppendLine(" |");
    }

    // =========================================================================
    // File Output
    // =========================================================================

    private static void WriteAtomically(
        string outputPath,
        string content)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(outputPath);
        ArgumentNullException.ThrowIfNull(content);

        var fullOutputPath = Path.GetFullPath(outputPath);

        var outputDirectory = Path.GetDirectoryName(
            fullOutputPath)
            ?? throw new InvalidOperationException(
                "The documentation index output directory " +
                "could not be determined.");

        Directory.CreateDirectory(outputDirectory);

        var temporaryPath = Path.Combine(
            outputDirectory,
            $".{Path.GetFileName(fullOutputPath)}." +
            $"{Guid.NewGuid():N}.tmp");

        try
        {
            File.WriteAllText(
                temporaryPath,
                content,
                new UTF8Encoding(
                    encoderShouldEmitUTF8Identifier: false));

            File.Move(
                temporaryPath,
                fullOutputPath,
                overwrite: true);
        }
        finally
        {
            if (File.Exists(temporaryPath))
            {
                File.Delete(temporaryPath);
            }
        }
    }

    // =========================================================================
    // Command Arguments
    // =========================================================================

    private static int HandleArguments(
        IReadOnlyList<string> arguments)
    {
        if (
            arguments.Count == 1 &&
            IsHelpRequest(arguments[0]))
        {
            PrintHelp();
            return 0;
        }

        Console.Error.WriteLine(
            $"Unknown index option '{arguments[0]}'.");

        Console.Error.WriteLine();
        PrintHelp();

        return 1;
    }

    private static bool IsHelpRequest(
        string value)
    {
        return string.Equals(
                   value,
                   "-h",
                   StringComparison.OrdinalIgnoreCase) ||
               string.Equals(
                   value,
                   "--help",
                   StringComparison.OrdinalIgnoreCase);
    }

    private static void PrintHelp()
    {
        Console.WriteLine("Usage:");

        Console.WriteLine(
            "  dotnet run --project tools/PiratePDF.DocGen -- index");

        Console.WriteLine();
        Console.WriteLine(
            "Generates docs/Documentation-Index.md from the " +
            "authoritative documentation library.");

        Console.WriteLine();
        Console.WriteLine("Options:");
        Console.WriteLine(
            "  -h, --help  Display index command help.");
    }

    // =========================================================================
    // Formatting Helpers
    // =========================================================================

    private static string EscapeTableValue(
        string value)
    {
        ArgumentNullException.ThrowIfNull(value);

        return value
            .Replace(
                "\\",
                "\\\\",
                StringComparison.Ordinal)
            .Replace(
                "|",
                "\\|",
                StringComparison.Ordinal);
    }

    private static string EscapeLinkTarget(
        string value)
    {
        ArgumentNullException.ThrowIfNull(value);

        return value
            .Replace(
                " ",
                "%20",
                StringComparison.Ordinal)
            .Replace(
                "(",
                "%28",
                StringComparison.Ordinal)
            .Replace(
                ")",
                "%29",
                StringComparison.Ordinal);
    }
}
