using System.Text;

using PiratePDF.DocGen.Generation;
using PiratePDF.DocGen.Models;
using PiratePDF.DocGen.Parsing;
using PiratePDF.DocGen.Validation;

var repositoryRoot = FindRepositoryRoot(
    Directory.GetCurrentDirectory());

var docsDirectory = Path.Combine(
    repositoryRoot,
    "docs");

var documentationIndexPath = Path.Combine(
    docsDirectory,
    "Documentation-Index.md");

var validationReportPath = Path.Combine(
    docsDirectory,
    "ValidationReport.md");

if (!Directory.Exists(docsDirectory))
{
    Console.Error.WriteLine(
        $"Documentation directory not found: {docsDirectory}");

    return 2;
}

try
{
    var documents = LoadDocuments(docsDirectory);

    GenerateDocumentationIndex(
        docsDirectory,
        documentationIndexPath,
        documents);

    var validationResult =
        DocumentationValidator.Validate(documents);

    ValidationReportWriter.Write(
        validationReportPath,
        repositoryRoot,
        documents.Count,
        validationResult);

    PrintSummary(
        documents.Count,
        validationResult,
        validationReportPath);

    return validationResult.HasErrors
        ? 1
        : 0;
}
catch (Exception exception)
{
    Console.Error.WriteLine(
        "Documentation processing failed.");

    Console.Error.WriteLine(exception);

    return 2;
}

static IReadOnlyList<DocumentMetadata> LoadDocuments(
    string docsDirectory)
{
    // Templates and generated outputs are excluded because they are not
    // authoritative project documents.
    var excludedFileNames = new HashSet<string>(
        StringComparer.OrdinalIgnoreCase)
    {
        "ADR-Template.md",
        "Document-Template.md",
        "Documentation-Index.md",
        "ValidationReport.md"
    };

    return Directory
        .EnumerateFiles(
            docsDirectory,
            "*.md",
            SearchOption.AllDirectories)
        .Where(path =>
            !excludedFileNames.Contains(
                Path.GetFileName(path)))
        .Select(MarkdownMetadataParser.Parse)
        .OrderBy(
            metadata => metadata.DocumentId,
            StringComparer.OrdinalIgnoreCase)
        .ThenBy(
            metadata => metadata.Title,
            StringComparer.OrdinalIgnoreCase)
        .ToArray();
}

static void GenerateDocumentationIndex(
    string docsDirectory,
    string outputPath,
    IReadOnlyCollection<DocumentMetadata> documents)
{
    var builder = new StringBuilder();

    builder.AppendLine("# PiratePDF Documentation Index");
    builder.AppendLine();
    builder.AppendLine("> This file is generated by PiratePDF.DocGen.");
    builder.AppendLine();

    builder.AppendLine(
        "| Document ID | Title | Category | Version | Status | Last Updated |");

    builder.AppendLine(
        "|---|---|---|---|---|---|");

    foreach (var document in documents)
    {
        var relativePath = Path
            .GetRelativePath(
                docsDirectory,
                document.FilePath)
            .Replace('\\', '/');

        builder.Append("| ");
        builder.Append(Escape(document.DocumentId));
        builder.Append(" | [");
        builder.Append(Escape(document.Title));
        builder.Append("](");
        builder.Append(relativePath);
        builder.Append(") | ");
        builder.Append(Escape(document.Category));
        builder.Append(" | ");
        builder.Append(Escape(document.Version));
        builder.Append(" | ");
        builder.Append(Escape(document.Status));
        builder.Append(" | ");
        builder.Append(Escape(document.LastUpdated));
        builder.AppendLine(" |");
    }

    File.WriteAllText(
        outputPath,
        builder.ToString(),
        new UTF8Encoding(
            encoderShouldEmitUTF8Identifier: false));
}

static void PrintSummary(
    int documentCount,
    DocumentationValidationResult result,
    string reportPath)
{
    Console.WriteLine("Documentation validation complete.");
    Console.WriteLine();
    Console.WriteLine($"Documents:  {documentCount}");
    Console.WriteLine($"Errors:     {result.ErrorCount}");
    Console.WriteLine($"Warnings:   {result.WarningCount}");
    Console.WriteLine($"Information:{result.InformationCount}");
    Console.WriteLine();
    Console.WriteLine($"Report: {reportPath}");
}

static string FindRepositoryRoot(
    string startingDirectory)
{
    var directory = new DirectoryInfo(
        startingDirectory);

    while (directory is not null)
    {
        var solutionPath = Path.Combine(
            directory.FullName,
            "PiratePDF.slnx");

        if (File.Exists(solutionPath))
        {
            return directory.FullName;
        }

        directory = directory.Parent;
    }

    throw new DirectoryNotFoundException(
        "Could not locate the PiratePDF repository root.");
}

static string Escape(
    string value)
{
    return value
        .Replace(
            "\\",
            "\\\\",
            StringComparison.Ordinal)
        .Replace(
            "|",
            "\\|",
            StringComparison.Ordinal);
}