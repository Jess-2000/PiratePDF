using PiratePDF.DocGen.Generation;
using System.Globalization;
using System.Text;

using PiratePDF.DocGen.Health;

namespace PiratePDF.DocGen.Reporting;

internal static class DocumentationHealthReportWriter
{
    // =========================================================================
    // Public API
    // =========================================================================

    public static void Write(
        string outputPath,
        DocumentationHealthSnapshot snapshot)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(outputPath);
        ArgumentNullException.ThrowIfNull(snapshot);

        var report = BuildReport(snapshot);

        WriteAtomically(
            outputPath,
            report);
    }

    // =========================================================================
    // Report Generation
    // =========================================================================

    private static string BuildReport(
        DocumentationHealthSnapshot snapshot)
    {
        var builder = new StringBuilder();

        builder.AppendLine(
            "# PiratePDF Documentation Health Report");

        builder.AppendLine();
        builder.AppendLine(
            "> This file is generated by PiratePDF.DocGen.");

        builder.AppendLine(
            "> Do not edit it manually.");

        builder.AppendLine();

        AppendInvariantLine(
            builder,
            "Generated: {0:yyyy-MM-dd HH:mm:ss} UTC",
            DateTimeOffset.UtcNow);

        builder.AppendLine();
        builder.AppendLine("## Overall Health");
        builder.AppendLine();
        builder.AppendLine("| Metric | Value |");
        builder.AppendLine("|---|---:|");

        AppendInvariantLine(
            builder,
            "| Score | {0:0.0}% |",
            snapshot.OverallScore);

        AppendInvariantLine(
            builder,
            "| Grade | {0} |",
            snapshot.Grade);

        builder.AppendLine();
        builder.AppendLine("## Library Statistics");
        builder.AppendLine();
        builder.AppendLine("| Metric | Count |");
        builder.AppendLine("|---|---:|");

        AppendCount(
            builder,
            "Documents",
            snapshot.DocumentCount);

        AppendCount(
            builder,
            "Sections",
            snapshot.SectionCount);

        AppendCount(
            builder,
            "Revision-history entries",
            snapshot.RevisionEntryCount);

        AppendCount(
            builder,
            "Related-document references",
            snapshot.RelatedDocumentReferenceCount);

        AppendCount(
            builder,
            "Related BF work-item references",
            snapshot.RelatedWorkItemReferenceCount);

        AppendGroupedCounts(
            builder,
            "Categories",
            snapshot.CategoryCounts);

        AppendGroupedCounts(
            builder,
            "Statuses",
            snapshot.StatusCounts);

        AppendGroupedCounts(
            builder,
            "Owners",
            snapshot.OwnerCounts);

        AppendCoverage(builder, snapshot);
        AppendValidation(builder, snapshot);
        AppendMissingRelationships(builder, snapshot);

        return builder.ToString();
    }

    private static void AppendCoverage(
        StringBuilder builder,
        DocumentationHealthSnapshot snapshot)
    {
        var coverage = snapshot.Coverage;

        builder.AppendLine();
        builder.AppendLine("## Coverage");
        builder.AppendLine();
        builder.AppendLine("| Area | Covered | Total | Percentage |");
        builder.AppendLine("|---|---:|---:|---:|");

        AppendCoverageRow(
            builder,
            "Document IDs",
            coverage.DocumentsWithDocumentId,
            coverage.TotalDocuments,
            coverage.DocumentIdPercentage);

        AppendCoverageRow(
            builder,
            "Versions",
            coverage.DocumentsWithVersion,
            coverage.TotalDocuments,
            coverage.VersionPercentage);

        AppendCoverageRow(
            builder,
            "Statuses",
            coverage.DocumentsWithStatus,
            coverage.TotalDocuments,
            coverage.StatusPercentage);

        AppendCoverageRow(
            builder,
            "Owners",
            coverage.DocumentsWithOwner,
            coverage.TotalDocuments,
            coverage.OwnerPercentage);

        AppendCoverageRow(
            builder,
            "Last-updated dates",
            coverage.DocumentsWithLastUpdated,
            coverage.TotalDocuments,
            coverage.LastUpdatedPercentage);

        AppendCoverageRow(
            builder,
            "Next-review dates",
            coverage.DocumentsWithNextReview,
            coverage.TotalDocuments,
            coverage.NextReviewPercentage);

        AppendCoverageRow(
            builder,
            "Revision histories",
            coverage.DocumentsWithRevisionHistory,
            coverage.TotalDocuments,
            coverage.RevisionHistoryPercentage);

        AppendCoverageRow(
            builder,
            "Related documents",
            coverage.DocumentsWithRelatedDocuments,
            coverage.TotalDocuments,
            coverage.RelatedDocumentsPercentage);

        AppendCoverageRow(
            builder,
            "Related BF work items",
            coverage.DocumentsWithRelatedWorkItems,
            coverage.TotalDocuments,
            coverage.RelatedWorkItemsPercentage);
    }

    private static void AppendValidation(
        StringBuilder builder,
        DocumentationHealthSnapshot snapshot)
    {
        builder.AppendLine();
        builder.AppendLine("## Validation");
        builder.AppendLine();
        builder.AppendLine("| Severity | Count |");
        builder.AppendLine("|---|---:|");

        AppendCount(
            builder,
            "Errors",
            snapshot.ValidationErrorCount);

        AppendCount(
            builder,
            "Warnings",
            snapshot.ValidationWarningCount);

        AppendCount(
            builder,
            "Information",
            snapshot.ValidationInformationCount);
    }

    private static void AppendMissingRelationships(
        StringBuilder builder,
        DocumentationHealthSnapshot snapshot)
    {
        builder.AppendLine();
        builder.AppendLine("## Missing Related Documents");
        builder.AppendLine();

        if (snapshot.MissingRelatedDocumentIds.Count == 0)
        {
            builder.AppendLine(
                "No missing related-document references were detected.");

            return;
        }

        foreach (var documentId in snapshot.MissingRelatedDocumentIds)
        {
            builder.Append("- `");
            builder.Append(documentId);
            builder.AppendLine("`");
        }
    }

    private static void AppendGroupedCounts(
        StringBuilder builder,
        string heading,
        IReadOnlyDictionary<string, int> counts)
    {
        builder.AppendLine();
        AppendInvariantLine(
            builder,
            "## {0}",
            heading);

        builder.AppendLine();
        builder.AppendLine("| Value | Count |");
        builder.AppendLine("|---|---:|");

        foreach (var pair in counts)
        {
            AppendInvariantLine(
                builder,
                "| {0} | {1} |",
                EscapeTableValue(pair.Key),
                pair.Value);
        }
    }

    private static void AppendCoverageRow(
        StringBuilder builder,
        string label,
        int covered,
        int total,
        double percentage)
    {
        AppendInvariantLine(
            builder,
            "| {0} | {1} | {2} | {3:0.0}% |",
            EscapeTableValue(label),
            covered,
            total,
            percentage);
    }

    private static void AppendCount(
        StringBuilder builder,
        string label,
        int count)
    {
        AppendInvariantLine(
            builder,
            "| {0} | {1} |",
            EscapeTableValue(label),
            count);
    }

    // =========================================================================
    // File Output
    // =========================================================================

    private static void WriteAtomically(
        string outputPath,
        string content)
    {
        var fullOutputPath = Path.GetFullPath(outputPath);

        var outputDirectory = Path.GetDirectoryName(
            fullOutputPath)
            ?? throw new InvalidOperationException(
                "The health-report output directory " +
                "could not be determined.");

        Directory.CreateDirectory(outputDirectory);

        var temporaryPath = Path.Combine(
            outputDirectory,
            $".{Path.GetFileName(fullOutputPath)}." +
            $"{Guid.NewGuid():N}.tmp");

        try
        {
            TrackedGeneratedFileWriter.WriteIfChanged(
                temporaryPath,
                content,
                new UTF8Encoding(
                    encoderShouldEmitUTF8Identifier: false));

            File.Move(
                temporaryPath,
                fullOutputPath,
                overwrite: true);
        }
        finally
        {
            if (File.Exists(temporaryPath))
            {
                File.Delete(temporaryPath);
            }
        }
    }

    // =========================================================================
    // Formatting Helpers
    // =========================================================================

    private static void AppendInvariantLine(
        StringBuilder builder,
        string format,
        params object?[] arguments)
    {
        ArgumentNullException.ThrowIfNull(builder);
        ArgumentException.ThrowIfNullOrWhiteSpace(format);
        ArgumentNullException.ThrowIfNull(arguments);

        builder.AppendFormat(
            CultureInfo.InvariantCulture,
            format,
            arguments);

        builder.AppendLine();
    }

    private static string EscapeTableValue(
        string value)
    {
        return value
            .Replace(
                "\\",
                "\\\\",
                StringComparison.Ordinal)
            .Replace(
                "|",
                "\\|",
                StringComparison.Ordinal);
    }
}