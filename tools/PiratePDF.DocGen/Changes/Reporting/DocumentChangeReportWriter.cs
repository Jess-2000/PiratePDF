using System.Globalization;
using System.Text;
using PiratePDF.DocGen.Generation;

namespace PiratePDF.DocGen.Changes.Reporting;

internal static class DocumentChangeReportWriter
{
    // =========================================================================
    // Public API
    // =========================================================================

    public static void Write(
        string outputPath,
        string repositoryRoot,
        DocumentChangeSet changeSet,
        bool changesApplied)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(outputPath);
        ArgumentException.ThrowIfNullOrWhiteSpace(repositoryRoot);
        ArgumentNullException.ThrowIfNull(changeSet);

        var report = BuildReport(
            repositoryRoot,
            changeSet,
            changesApplied);

        WriteAtomically(
            outputPath,
            report);
    }

    // =========================================================================
    // Report Generation
    // =========================================================================

    private static string BuildReport(
        string repositoryRoot,
        DocumentChangeSet changeSet,
        bool changesApplied)
    {
        var builder = new StringBuilder();

        builder.AppendLine("# PiratePDF Document Change Report");
        builder.AppendLine();
        builder.AppendLine(
            "> This file is generated by PiratePDF.DocGen.");

        builder.AppendLine(
            "> Do not edit it manually.");

        builder.AppendLine();

        AppendInvariantLine(
            builder,
            "Generated: {0:yyyy-MM-dd HH:mm:ss} UTC",
            DateTimeOffset.UtcNow);

        builder.AppendLine();
        builder.AppendLine("## Summary");
        builder.AppendLine();
        builder.AppendLine("| Metric | Value |");
        builder.AppendLine("|---|---:|");

        AppendInvariantLine(
            builder,
            "| Changes | {0} |",
            changeSet.Count);

        AppendInvariantLine(
            builder,
            "| Files | {0} |",
            changeSet.FileCount);

        AppendInvariantLine(
            builder,
            "| Applied | {0} |",
            changesApplied ? "Yes" : "No");

        AppendChangeTypeCounts(
            builder,
            changeSet);

        builder.AppendLine();
        builder.AppendLine("## Proposed Changes");
        builder.AppendLine();

        if (changeSet.IsEmpty)
        {
            builder.AppendLine(
                "No document changes were proposed.");

            return builder.ToString();
        }

        foreach (var fileGroup in changeSet.Changes.GroupBy(
                     change => change.FilePath,
                     StringComparer.OrdinalIgnoreCase))
        {
            var relativePath = Path
                .GetRelativePath(
                    repositoryRoot,
                    fileGroup.Key)
                .Replace('\\', '/');

            builder.Append("### `");
            builder.Append(relativePath);
            builder.AppendLine("`");
            builder.AppendLine();

            foreach (var change in fileGroup.OrderBy(
                         change => change.StartIndex))
            {
                AppendChange(
                    builder,
                    change);
            }
        }

        return builder.ToString();
    }

    private static void AppendChangeTypeCounts(
        StringBuilder builder,
        DocumentChangeSet changeSet)
    {
        foreach (var pair in changeSet.GetChangeTypeCounts())
        {
            AppendInvariantLine(
                builder,
                "| {0} changes | {1} |",
                EscapeTableValue(pair.Key),
                pair.Value);
        }
    }

    private static void AppendChange(
        StringBuilder builder,
        DocumentChange change)
    {
        AppendInvariantLine(
            builder,
            "- **Type:** {0}",
            change.ChangeType);

        AppendInvariantLine(
            builder,
            "- **Start index:** {0}",
            change.StartIndex);

        AppendInvariantLine(
            builder,
            "- **Length:** {0}",
            change.Length);

        AppendInvariantLine(
            builder,
            "- **Reason:** {0}",
            EscapeInlineText(change.Reason));

        if (change.ReplacementText.Length > 0)
        {
            builder.AppendLine("- **Replacement:**");
            builder.AppendLine();
            builder.AppendLine("```text");
            builder.AppendLine(change.ReplacementText);
            builder.AppendLine("```");
        }

        builder.AppendLine();
    }

    // =========================================================================
    // File Output
    // =========================================================================

    private static void WriteAtomically(
        string outputPath,
        string content)
    {
        var fullOutputPath = Path.GetFullPath(outputPath);

        var directory = Path.GetDirectoryName(fullOutputPath)
            ?? throw new InvalidOperationException(
                "The change-report directory could not be determined.");

        Directory.CreateDirectory(directory);

        TrackedGeneratedFileWriter.WriteIfChanged(
            fullOutputPath,
            content,
            new UTF8Encoding(
                encoderShouldEmitUTF8Identifier: false));
    }

    // =========================================================================
    // Formatting Helpers
    // =========================================================================

    private static void AppendInvariantLine(
        StringBuilder builder,
        string format,
        params object?[] arguments)
    {
        ArgumentNullException.ThrowIfNull(builder);
        ArgumentException.ThrowIfNullOrWhiteSpace(format);
        ArgumentNullException.ThrowIfNull(arguments);

        builder.AppendFormat(
            CultureInfo.InvariantCulture,
            format,
            arguments);

        builder.AppendLine();
    }

    private static string EscapeTableValue(
        string value)
    {
        return value.Replace(
            "|",
            "\\|",
            StringComparison.Ordinal);
    }

    private static string EscapeInlineText(
        string value)
    {
        return value
            .Replace(
                "\r",
                " ",
                StringComparison.Ordinal)
            .Replace(
                "\n",
                " ",
                StringComparison.Ordinal);
    }
}
